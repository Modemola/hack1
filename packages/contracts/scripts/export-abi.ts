// Writes abi.ts with typed ABIs for the web app (run after compile).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const names = ["PakkaRegistry", "JoiningGuarantee", "TestUSD"];
let out = "// Generated by scripts/export-abi.ts. Do not edit.\n\n";
for (const n of names) {
  const art = JSON.parse(readFileSync(path.join(__dirname, "..", "artifacts", "contracts", `${n}.sol`, `${n}.json`), "utf8"));
  out += `export const ${n[0].toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n\n`;
}
writeFileSync(path.join(__dirname, "..", "abi.ts"), out);
console.log("abi.ts written");
